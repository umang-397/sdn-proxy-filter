#!/usr/bin/env python3
"""Concurrent TCP proxy with policy based allow/deny.

Request format (one text line):   GET <service>/<resource>
Replies generated by the proxy:   BLOCKED <reason> | ERROR <text>
Allowed requests are forwarded to the service as "GET /<resource>" and the
service's answer is relayed back to the client.

Runtime control (only reachable on 127.0.0.1 of the proxy host), see ctl.py:
  BLOCK <service> | ALLOW <service> | BLOCKCLIENT <ip> | ALLOWCLIENT <ip>
  RELOAD | SHOW | STATS
Every policy change is pushed to the SDN controller over a unix socket so the
controller installs / removes a matching drop rule in the switch.
"""
import argparse
import json
import re
import socket
import threading
import time

from policy import Policy

REQ = re.compile(r"^GET ([A-Za-z0-9_-]+)/(\S*)$")


class Proxy:
    def __init__(self, a):
        with open(a.config) as f:
            self.cfg = json.load(f)
        self.args = a
        self.policy = Policy(a.policy)
        self.pip = self.cfg["proxy"]["ip"]
        self.services = self.cfg["services"]
        self.stats = {"permitted": 0, "blocked": 0, "errors": 0}
        self.stats_lock = threading.Lock()
        self.log_lock = threading.Lock()
        self.sync_lock = threading.Lock()
        self.synced = set()          # (src, dst) drops already pushed to controller
        self.sync()

    # ------------------------------------------------------------ logging
    def log(self, client, service, resource, action, reason):
        key = {"permit": "permitted", "block": "blocked"}.get(action, "errors")
        with self.stats_lock:
            self.stats[key] += 1
        line = "%s,%s,%s,%s,%s,%s\n" % (
            time.strftime("%Y-%m-%d %H:%M:%S"), client, service,
            resource.replace(",", "_")[:60], action, reason)
        with self.log_lock, open(self.args.log, "a") as f:
            f.write(line)

    # --------------------------------------------------- controller link
    def notify(self, cmd):
        try:
            s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            s.settimeout(2)
            s.connect(self.cfg["controller_sock"])
            s.sendall((cmd + "\n").encode())
            reply = s.recv(200).decode().strip()
            s.close()
            return reply
        except OSError as e:
            return "ERR " + str(e)

    def desired_drops(self):
        want = set()
        for r in self.policy.rules:
            if r["action"] != "deny" or r.get("keyword"):
                continue
            c, s = r.get("client", "*"), r.get("service", "*")
            if c == "*" and s in self.services:
                want.add((self.pip, self.services[s]["ip"]))   # proxy -> service
            elif s == "*" and c != "*":
                want.add((c, self.pip))                         # client -> proxy
        return want

    def sync(self):
        """Make the controller's drop rules match the policy. Returns (ms, acks)."""
        with self.sync_lock:
            t0 = time.time()
            want = self.desired_drops()
            acks = []
            for p in sorted(want - self.synced):
                a = self.notify("DROP %s %s" % p)
                acks.append(a)
                if a.startswith("OK"):
                    self.synced.add(p)
            for p in sorted(self.synced - want):
                a = self.notify("ALLOW %s %s" % p)
                acks.append(a)
                if a.startswith("OK"):
                    self.synced.discard(p)
            return (time.time() - t0) * 1000, acks

    # ------------------------------------------------------ client side
    @staticmethod
    def reply(conn, text):
        try:
            conn.sendall(text.encode())
        except OSError:
            pass

    def handle(self, conn, addr):
        client = addr[0]
        conn.settimeout(5)
        try:
            if self.policy.changed_on_disk():       # policy file edited by hand
                self.policy.load()
                self.sync()
            buf = b""
            while b"\n" not in buf and len(buf) < 1024:
                chunk = conn.recv(256)
                if not chunk:
                    break
                buf += chunk
            line = buf.split(b"\n")[0].decode(errors="replace").strip()
            m = REQ.match(line)
            if not m:
                self.reply(conn, "ERROR malformed request\n")
                self.log(client, "-", line, "error", "malformed")
                return
            service, resource = m.groups()
            action, reason = self.policy.decide(client, service, resource)
            if action == "deny":
                self.reply(conn, "BLOCKED %s\n" % reason)
                self.log(client, service, resource, "block", reason)
                return
            svc = self.services.get(service)
            if not svc:
                self.reply(conn, "ERROR unknown service\n")
                self.log(client, service, resource, "error", "unknown service")
                return
            try:
                up = socket.create_connection((svc["ip"], svc["port"]), timeout=3)
            except OSError:
                self.reply(conn, "ERROR service unavailable\n")
                self.log(client, service, resource, "error", "service down")
                return
            with up:
                up.settimeout(10)
                up.sendall(("GET /%s\n" % resource).encode())
                while True:
                    data = up.recv(65536)
                    if not data:
                        break
                    conn.sendall(data)
            self.log(client, service, resource, "permit", reason)
        except OSError as e:                         # slow client / dropped
            self.log(client, "-", "-", "error", "client io: %s" % e)
        finally:
            conn.close()

    # ---------------------------------------------------- control side
    def command(self, line):
        t0 = time.time()
        parts = line.split()
        if not parts:
            return "ERR empty"
        cmd, arg = parts[0].upper(), (parts[1] if len(parts) > 1 else None)
        if cmd == "STATS":
            return json.dumps(self.stats)
        if cmd == "SHOW":
            return json.dumps({"default": self.policy.default, "rules": self.policy.rules})
        if cmd in ("BLOCK", "ALLOW") and arg not in self.services:
            return "ERROR unknown service"
        table = {"BLOCK": self.policy.block_service, "ALLOW": self.policy.allow_service,
                 "BLOCKCLIENT": self.policy.block_client, "ALLOWCLIENT": self.policy.allow_client}
        if cmd in table and arg:
            table[cmd](arg)
        elif cmd == "RELOAD":
            self.policy.load()
        else:
            return "ERR unknown command"
        _, acks = self.sync()
        return "OK policy active after %.1f ms, controller: %s" % (
            (time.time() - t0) * 1000, acks or "no change")

    def control_loop(self):
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind(("127.0.0.1", self.args.ctl_port))
        s.listen(5)
        while True:
            c, _ = s.accept()
            try:
                c.settimeout(3)
                line = c.recv(200).decode().strip()
                c.sendall((self.command(line) + "\n").encode())
            except OSError:
                pass
            finally:
                c.close()

    def serve(self):
        threading.Thread(target=self.control_loop, daemon=True).start()
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind((self.args.listen, self.args.port))
        s.listen(128)
        print("proxy listening on %s:%d" % (self.args.listen, self.args.port), flush=True)
        while True:
            conn, addr = s.accept()
            threading.Thread(target=self.handle, args=(conn, addr), daemon=True).start()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="config/network.json")
    ap.add_argument("--policy", default="config/policy.json")
    ap.add_argument("--log", default="logs/proxy.log")
    ap.add_argument("--listen", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--ctl-port", type=int, default=9000)
    Proxy(ap.parse_args()).serve()


if __name__ == "__main__":
    main()
